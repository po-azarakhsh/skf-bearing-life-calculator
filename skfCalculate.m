function R = skfCalculate(D,B,oils,I)
%SKFCALCULATE Complete calculation chain with an inspectable calculation log.
% I: bearing, design, speed, oil_grade, temperature, D_mm, d_mm, eta_c, Pu, P, method.
R=struct('dm',NaN,'nu1',NaN,'nu_oil',NaN,'kappa',NaN,'kappa_used',NaN, ...
    'q',NaN,'aSKF',NaN,'ndm',NaN,'status',"",'log',strings(0,1), ...
    'rated_info',[],'oil_info',[],'life_info',[],'inputs',I);
L=["SKF bearing lubrication and life calculation"; ...
    "Time: "+string(datetime('now','Format','yyyy-MM-dd HH:mm:ss')); ...
    sprintf('Bearing diagram: %d; design: %s; chart model: %s',I.bearing,I.design,I.method); ...
    sprintf('n = %.12g rpm; oil = Amokon ISO VG %g; T = %.12g C',I.speed,I.oil_grade,I.temperature); ...
    sprintf('D = %.12g mm; d = %.12g mm; eta_c = %.12g; Pu = %.12g kN; P = %.12g kN',I.D_mm,I.d_mm,I.eta_c,I.Pu,I.P)];
if any(~isfinite([I.D_mm I.d_mm I.speed I.temperature I.eta_c I.Pu I.P])) || ...
        I.d_mm<=0 || I.D_mm<=I.d_mm || I.Pu<=0 || I.P<=0 || I.eta_c<=0 || I.eta_c>1
    R.status="Invalid inputs: require D > d > 0, Pu > 0, P > 0, and 0 < eta_c <= 1.";
    R.log=[L;R.status];return
end
R.dm=(I.D_mm+I.d_mm)/2;R.ndm=I.speed*R.dm;R.q=I.eta_c*I.Pu/I.P;
L=[L;"";sprintf('d_m = (D + d)/2 = (%.12g + %.12g)/2 = %.12g mm',I.D_mm,I.d_mm,R.dm); ...
    sprintf('n*d_m = %.12g * %.12g = %.12g mm/min',I.speed,R.dm,R.ndm); ...
    sprintf('q = eta_c*Pu/P = %.12g * %.12g / %.12g = %.12g',I.eta_c,I.Pu,I.P,R.q)];
oi=find([oils.grade]==I.oil_grade,1);
if isempty(oi),R.status="Selected oil is absent from the database.";R.log=[L;R.status];return,end
[R.nu_oil,oilStatus,R.oil_info]=skfOilViscosity(oils(oi),I.temperature);
O=R.oil_info;
L=[L;"";"OIL VISCOSITY";"Source: "+string(O.source_file); ...
    sprintf('Read numeric column 4: kinematic viscosity, cSt = mm^2/s. %d source rows.',oils(oi).row_count); ...
    'Temperature grid: T_C = (T_F - 32)*5/9; rounded source Celsius is not used.'; ...
    sprintf('Temperature bracket: [%.12g, %.12g] C; source viscosities: [%.12g, %.12g] mm^2/s',O.bracket_temperature_C,O.bracket_viscosity); ...
    'Method: PCHIP(T_C, log10(nu_oil)), then 10^interpolated_value.'; ...
    sprintf('nu_oil = %.12g mm^2/s',R.nu_oil);oilStatus];
[R.nu1,ratedStatus,R.rated_info]=skfRatedViscosity(B,R.dm,I.speed,string(I.method));
V=R.rated_info;
L=[L;"";"RATED VISCOSITY - DIAGRAM 14"; ...
    'Source: Life Modification.pdf, PDF page 8, catalogue page 101.'; ...
    'Horizontal: d_m [mm]. Vertical: nu_1 [mm^2/s]. Lines: speed n [rpm].'; ...
    sprintf('Speed bracket: [%.12g, %.12g] rpm; log-speed weight = %.12g',V.speed_bracket,V.speed_weight); ...
    sprintf('Visible diameter overlap: [%.12g, %.12g] mm',V.diameter_overlap); ...
    "Within each speed curve: "+string(I.method)+" in log(d_m), log(nu_1)."];
if ~isempty(V.nu1_bracket)
    L=[L;sprintf('nu_1 on bracketing curves: [%.12g, %.12g] mm^2/s',V.nu1_bracket(1,:)); ...
        'log10(nu_1) = (1-w)*log10(nu_low) + w*log10(nu_high).'];
end
L=[L;sprintf('nu_1 = %.12g mm^2/s',R.nu1);ratedStatus];
if isfinite(R.nu1)&&isfinite(R.nu_oil)
    R.kappa=R.nu_oil/R.nu1;R.kappa_used=min(R.kappa,4);
end
L=[L;"";sprintf('kappa = nu_oil / nu_1 = %.12g / %.12g = %.12g',R.nu_oil,R.nu1,R.kappa); ...
    sprintf('kappa used for aSKF = %.12g (source cap at 4; actual kappa remains displayed)',R.kappa_used)];
if R.ndm<=10000
    L=[L;'Diagram 14 low n*d_m area (<= 10000): source notes EP/AW additives for wear.'];
elseif (R.dm<=200 && R.ndm>=500000)||(R.dm>200 && R.ndm>=400000)
    L=[L;'Diagram 14 high n*d_m area: source notes operating-temperature considerations.'];
end
idx=find([D.sets.diagram]==I.bearing & strcmp({D.sets.design},I.design),1);
if isempty(idx),R.status="No matching life diagram.";
elseif ~isfinite(R.kappa)
    R.status="aSKF unavailable: oil viscosity or rated viscosity could not be determined.";
else
    S=D.sets(idx);[R.aSKF,R.status,R.life_info]=skfEvaluate(S,R.kappa,R.q,string(I.method));
    L=[L;"";sprintf('LIFE DIAGRAM %d - %s',S.diagram,S.design); ...
        sprintf('q domain = [%.12g, %.12g]; requested q = %.12g',S.bounds,R.q)];
    F=R.life_info;
    if ~isempty(F.kappa_bracket)
        L=[L;sprintf('kappa bracket = [%.12g, %.12g]; log-kappa weight = %.12g',F.kappa_bracket,F.kappa_weight)];
    end
    if ~isempty(F.a_bracket)
        L=[L;sprintf('aSKF on bracketing curves = [%.12g, %.12g]',F.a_bracket(1,:)); ...
            'log10(aSKF) = (1-w)*log10(a_low) + w*log10(a_high).'];
    end
end
R.log=[L;"";sprintf('FINAL aSKF = %.12g',R.aSKF);R.status; ...
    'Unlabelled life curves k=1.5 and k=3 retain their assumed labels.'; ...
    'No temperature, speed, diameter, or q extrapolation. Digitized charts are approximate.'];
end
